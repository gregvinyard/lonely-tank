export const FONT_CHARS = Object.keys(GLYPHS).join('');
export const FONT_COLS = 16;

/** Lit pixels of every glyph, in sheet coordinates (FONT_COLS glyphs per row). */
export function fontPixels(): { width: number; height: number; pixels: [number, number][] } {
  const chars = Object.keys(GLYPHS);
  const pixels: [number, number][] = [];
  chars.forEach((ch, i) => {
    const ox = (i % FONT_COLS) * CELL_W;
    const oy = Math.floor(i / FONT_COLS) * CELL_H;
    GLYPHS[ch].split(' ').forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') pixels.push([ox + x, oy + y]);
    });
  });
  return { width: FONT_COLS * CELL_W, height: Math.ceil(chars.length / FONT_COLS) * CELL_H, pixels };
}

/** Text as the font can show it: uppercase, unknown characters replaced by '?'. */
export function toFontText(text: string): string {
  return Array.from(text.toUpperCase(), (c) => (c === '\n' || c in GLYPHS ? c : '?')).join('');
}

export function glyphRows(ch: string): string[] | undefined {
  return GLYPHS[ch]?.split(' ');
}
